def graph(a):
    """for each operator (k: 0 = the sixth): is it a carrier, whom does it modulate (k), is it the feedback one"""
    bus = {1: [], 2: []}
    car, tgt, fbop = [False] * 6, [None] * 6, None
    for k in range(6):
        f = ALG[a][k]
        inb = (f >> 4) & 3
        if inb:
            for m in bus[inb]:
                tgt[m] = k
        if f & 0x40:
            fbop = k
        out = f & 3
        if out == 0:
            car[k] = True
        else:
            if f & 4:
                bus[out].append(k)
            else:
                bus[out] = [k]
    # (a modulator's target: the operator that reads its bus; carriers' "bus 0")
    return car, tgt, fbop
