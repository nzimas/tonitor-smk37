def kmeans(X, k, it=80, seed=1):
    import numpy as np
    rng = np.random.default_rng(seed)
    C = X[rng.choice(len(X), 1)]
    for _ in range(k - 1):                              # k-means++
        d = ((X[:, None, :] - C[None]) ** 2).sum(2).min(1)
        C = np.vstack([C, X[rng.choice(len(X), 1, p=d / d.sum())]])
    for _ in range(it):
        L = ((X[:, None, :] - C[None]) ** 2).sum(2).argmin(1)
        C = np.array([X[L == j].mean(0) if (L == j).any() else C[j] for j in range(k)])
    return L, C
